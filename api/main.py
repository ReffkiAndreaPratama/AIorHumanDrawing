"""
api/main.py
FastAPI backend for the AI vs Human Drawing Detector.

Endpoints:
  GET  /              — health check
  POST /predict       — upload image, get prediction + features
  GET  /model/info    — model metadata

Run:
    uvicorn api.main:app --reload --port 8000
"""

import sys
import time
import joblib
from pathlib import Path
from contextlib import asynccontextmanager

from fastapi import FastAPI, File, UploadFile, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse
from pydantic import BaseModel

# Make sure project root is on the path when running from repo root
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.predict import predict_from_bytes, PredictionResult

MODEL_PATH = Path("model/drawing_detector.joblib")

# ─── Lifespan ─────────────────────────────────────────────────────────────────

@asynccontextmanager
async def lifespan(app: FastAPI):
    """Pre-warm the model on startup so the first request is fast."""
    if MODEL_PATH.exists():
        import src.predict as _pred
        _pred.get_model()   # loads + caches model
        print("[API] Model loaded and cached.")
    else:
        print("[API] WARN — model file not found. "
              "Run `python src/train.py` before serving predictions.")
    yield


# ─── App ──────────────────────────────────────────────────────────────────────

app = FastAPI(
    title="AI vs Human Drawing Detector",
    description=(
        "Upload a drawing or sketch and get a probability estimate of "
        "whether it was created by a human or generated by AI. "
        "Results are model estimates based on learned visual patterns — "
        "not a definitive forensic determination."
    ),
    version="1.0.0",
    lifespan=lifespan,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],   # tighten this for production
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# ─── Schemas ──────────────────────────────────────────────────────────────────

class PredictionResponse(BaseModel):
    label: str
    confidence: float
    human_prob: float
    ai_prob: float
    display_features: dict
    inference_time_ms: float
    disclaimer: str


class HealthResponse(BaseModel):
    status: str
    model_loaded: bool
    version: str


class ModelInfoResponse(BaseModel):
    model_path: str
    model_exists: bool
    feature_groups: list[str]
    classes: list[str]
    note: str


# ─── Helpers ──────────────────────────────────────────────────────────────────

ALLOWED_MIME = {
    "image/jpeg",
    "image/png",
    "image/bmp",
    "image/webp",
    "image/tiff",
}

MAX_FILE_SIZE_MB = 10
DISCLAIMER = (
    "This result is a statistical estimate based on visual patterns "
    "learned from training data. It is not a forensic determination. "
    "Post-processed, compressed, or edited images may produce less "
    "reliable results."
)


def validate_upload(file: UploadFile) -> None:
    """Raise HTTPException for invalid uploads."""
    if file.content_type not in ALLOWED_MIME:
        raise HTTPException(
            status_code=415,
            detail=(
                f"Unsupported media type: {file.content_type}. "
                f"Supported: {', '.join(sorted(ALLOWED_MIME))}"
            ),
        )


# ─── Routes ───────────────────────────────────────────────────────────────────

@app.get("/", response_model=HealthResponse, tags=["Health"])
async def health_check():
    """Returns API health status and whether the model is loaded."""
    return HealthResponse(
        status="ok",
        model_loaded=MODEL_PATH.exists(),
        version="1.0.0",
    )


@app.post("/predict", response_model=PredictionResponse, tags=["Prediction"])
async def predict(file: UploadFile = File(...)):
    """
    Upload a drawing/sketch image and receive:
    - **label**: Human | AI | Uncertain
    - **confidence**: probability of the predicted class (0–1)
    - **human_prob** / **ai_prob**: full class probabilities
    - **display_features**: curated image analysis metrics shown in the UI
    - **inference_time_ms**: processing time

    Accepted formats: JPEG, PNG, BMP, WebP, TIFF (max 10 MB).
    """
    validate_upload(file)

    image_bytes = await file.read()

    # Enforce size limit
    size_mb = len(image_bytes) / (1024 * 1024)
    if size_mb > MAX_FILE_SIZE_MB:
        raise HTTPException(
            status_code=413,
            detail=f"File too large ({size_mb:.1f} MB). Maximum is {MAX_FILE_SIZE_MB} MB.",
        )

    if not MODEL_PATH.exists():
        raise HTTPException(
            status_code=503,
            detail="Model not available. Run `python src/train.py` to train first.",
        )

    try:
        t0 = time.perf_counter()
        result: PredictionResult = predict_from_bytes(image_bytes)
        elapsed_ms = (time.perf_counter() - t0) * 1000
    except ValueError as e:
        raise HTTPException(status_code=422, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Inference error: {e}")

    return PredictionResponse(
        label=result.label,
        confidence=round(result.confidence, 4),
        human_prob=round(result.human_prob, 4),
        ai_prob=round(result.ai_prob, 4),
        display_features=result.display_features,
        inference_time_ms=round(elapsed_ms, 2),
        disclaimer=DISCLAIMER,
    )


@app.get("/model/info", response_model=ModelInfoResponse, tags=["Model"])
async def model_info():
    """Returns metadata about the loaded model and feature pipeline."""
    return ModelInfoResponse(
        model_path=str(MODEL_PATH),
        model_exists=MODEL_PATH.exists(),
        feature_groups=[
            "GLCM (contrast, dissimilarity, homogeneity, energy, correlation, ASM)",
            "Edge (density, gradient mean/std/max, Laplacian variance)",
            "Frequency domain (FFT low/high freq ratio)",
            "Statistical (entropy, pixel mean/std, local variance)",
            "Color (HSV hue/saturation/value mean, std, entropy)",
            "Noise (Gaussian residual std and mean absolute)",
        ],
        classes=["Human", "AI"],
        note=(
            "Classifier: Soft-voting ensemble of SVM (RBF) + Random Forest (300 trees). "
            "Input: 256×256 grayscale/color image → ~50 handcrafted features."
        ),
    )
